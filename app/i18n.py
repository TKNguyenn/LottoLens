_TOKEN = re.compile(r"\{(\d+)\}")


def _compile_templates():
    templates = []
    for source, target in sorted(_EN.items(), key=lambda item: len(item[0]), reverse=True):
        tokens = list(_TOKEN.finditer(source))
        if not tokens or not any(character.isalpha() for character in _TOKEN.sub("", source)):
            continue
        parts, seen, end = [], set(), 0
        for token in tokens:
            index = token.group(1)
            parts.append(re.escape(source[end:token.start()]))
            parts.append(f"(?P=p{index})" if index in seen else f"(?P<p{index}>.*?)")
            seen.add(index)
            end = token.end()
        parts.append(re.escape(source[end:]))
        templates.append((re.compile("".join(parts), re.S), target))
    return tuple(templates)


_TEMPLATES = _compile_templates()


def set_language(code):
    """Select the language for subsequent tr calls; unsupported codes use Vietnamese."""
    global _language
    _language = code if code in ("vi", "en") else "vi"


def tr(text):
    """Translate owned display copy without rewriting interpolated data or unknown text."""
    if _language != "en":
        return text
    if text in _EN:
        return _EN[text]
    for pattern, target in _TEMPLATES:
        match = pattern.fullmatch(text)
        if match:
            return _TOKEN.sub(lambda token: match.group("p" + token.group(1)), target)
    return text


def bind_text(widget, setter, source):
    """Retain canonical display copy for later language changes, then render it."""
    widget.setProperty("i18n_" + setter, source)
    getattr(widget, setter)(tr(source))


